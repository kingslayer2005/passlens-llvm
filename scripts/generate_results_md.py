#!/usr/bin/env python3
"""
generate_results_md.py — Build results/RESULTS.md from the result files.

Every number in RESULTS.md is read from a file in results/.  Nothing is
typed by hand, and a section whose file does not exist says NOT RUN.

Usage:
  python -m scripts.generate_results_md
"""

import json
import sys
from pathlib import Path
from typing import List, Optional

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from scripts.utils import RESULTS_DIR, setup_logging

log = setup_logging("results_md")

NOT_RUN = "**NOT RUN.** The file this section is built from does not exist.\n"


def read_csv(name: str) -> Optional[pd.DataFrame]:
    """Read a result table, or None if the phase that writes it has not run."""
    path = RESULTS_DIR / name
    if not path.exists() or path.stat().st_size < 5:
        return None
    try:
        return pd.read_csv(path)
    except pd.errors.EmptyDataError:
        return None


def markdown_table(df: pd.DataFrame, columns: Optional[List[str]] = None) -> str:
    """A plain Markdown table (written out here to avoid an extra dependency)."""
    if columns:
        df = df[[c for c in columns if c in df.columns]]
    if df.empty:
        return "_(no rows)_\n"

    def cell(value) -> str:
        if value is None or (isinstance(value, float) and value != value):
            return ""
        if isinstance(value, float):
            return f"{value:.4g}"
        return str(value).replace("|", "/")

    lines = ["| " + " | ".join(df.columns) + " |",
             "|" + "|".join("---" for _ in df.columns) + "|"]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join(cell(v) for v in row) + " |")
    return "\n".join(lines) + "\n"


def text_block(name: str) -> str:
    """A gate report, shown as it was written."""
    path = RESULTS_DIR / name
    if not path.exists():
        return NOT_RUN
    return "```\n" + path.read_text(encoding="utf-8").rstrip() + "\n```\n"


def generate():
    """Write results/RESULTS.md."""
    parts = ["# Results\n",
             "This file is generated by `scripts/generate_results_md.py` from the files in "
             "`results/`. Do not edit it by hand.\n"]

    # ---- Which settings produced the analysis files? ----
    params_path = RESULTS_DIR / "phase4_tuned_params.json"
    settings = None
    if params_path.exists():
        settings = json.loads(params_path.read_text(encoding="utf-8")).get("settings")
    if settings == "smoke":
        parts.append("> **SMOKE RUN.** The model, SHAP and sequence sections below were "
                     "produced with tiny test settings on a few passes. They show that the "
                     "code runs. **They are not results and must not be cited.**\n")
    elif settings is None:
        parts.append("> Models and explanations (Phases 4-7) have **not been run**. "
                     "Only the data sections below contain results.\n")

    # ---- Data ----
    parts += ["## 1. Data (Phases 1-3)\n", text_block("phase1_gate.txt"),
              text_block("phase3_gate.txt")]

    # ---- Master table ----
    parts.append("## 2. Status of every pass x target\n")
    master = read_csv("master_table.csv")
    if master is None:
        parts.append(NOT_RUN)
    else:
        parts.append(
            "A target is *kept* when its positive rate is between 5 % and 95 %. It is "
            "*interpreted* only if XGBoost beats the majority baseline (Holm-corrected "
            "Wilcoxon test and program bootstrap) and its SHAP ranking is stable "
            "(Kendall tau of at least 0.6 across folds).\n")
        if "interpretation_status" in master:
            status = master["interpretation_status"].fillna("")
            reason = master["interpretation_reason"].fillna("")
        else:
            status = master["model_status"].fillna("") + " (Phase 5 not run)"
            reason = master["model_reason"].fillna("")
        table = master[["pass_name", "target", "positive_rate"]].copy()
        table["status"] = status
        table["reason"] = reason
        for column in ("xgboost_pr_auc", "majority_pr_auc", "shap_stability_tau"):
            if column in master:
                table[column] = master[column]
        parts.append(markdown_table(table))
        counts = table["status"].value_counts()
        parts.append("Counts: " + ", ".join(f"{k}: {v}" for k, v in counts.items()) + ".\n")

    # ---- Models ----
    parts.append("## 3. Predictive performance (Phase 4)\n")
    summary = read_csv("phase4_summary.csv")
    if summary is None:
        parts.append(NOT_RUN)
    else:
        parts.append("Mean PR-AUC over the outer folds (grouped by benchmark program).\n")
        wide = summary.pivot_table(index=["pass_name", "target"], columns="model",
                                   values="pr_auc_mean", sort=False).reset_index()
        parts.append(markdown_table(wide, ["pass_name", "target", "majority",
                                           "logistic_regression", "random_forest", "xgboost"]))
        comparison = read_csv("phase4_wilcoxon.csv")
        if comparison is not None:
            parts.append("XGBoost against the majority baseline:\n")
            parts.append(markdown_table(
                comparison[comparison["baseline"] == "majority"],
                ["pass_name", "target", "n_folds", "mean_difference", "p_holm",
                 "diff_ci_low", "diff_ci_high", "xgboost_better"]))
        cross = read_csv("phase4_cross_suite.csv")
        if cross is not None:
            parts.append("Trained on one benchmark suite, tested on the other:\n")
            parts.append(markdown_table(cross, ["pass_name", "target", "train_suite", "test_suite",
                                                "n_train", "n_test", "pos_rate_test",
                                                "xgboost_pr_auc", "note"]))
        parts.append("Leakage audit: see `leakage_audit.txt` (one line per fold). "
                     "Skipped folds: see `skipped_folds.txt`.\n")

    # ---- SHAP ----
    parts.append("## 4. Can the explanations be trusted? (Phase 5)\n")
    checks = read_csv("shap_checks.csv")
    if checks is None:
        parts.append(NOT_RUN)
    else:
        parts.append(
            "`stability_tau`: agreement of the feature ranking across folds. "
            "`dual_method_tau`: path-dependent vs interventional SHAP. "
            "`shuffled_labels_pr_auc` should be close to `chance_pr_auc`.\n")
        parts.append(markdown_table(checks, [
            "pass_name", "target", "interpreted", "n_folds", "stability_tau", "top10_overlap",
            "dual_method_tau", "permutation_importance_tau", "shuffled_labels_pr_auc",
            "chance_pr_auc", "ranking_tau_without_size_features"]))
        faith = read_csv("faithfulness.csv")
        if faith is not None:
            parts.append("Faithfulness: PR-AUC lost when the top-k SHAP features are removed, "
                         "against k random features.\n")
            parts.append(markdown_table(faith, ["pass_name", "target", "interpreted", "k",
                                                "full_pr_auc", "drop_top_shap", "drop_random",
                                                "folds_where_shap_hurts_more", "n_folds"]))

    parts.append("## 5. What drives each decision (Phase 5)\n")
    rankings = read_csv("shap_rankings.csv")
    if rankings is None:
        parts.append(NOT_RUN)
    else:
        top = rankings[(rankings["rank"] <= 5) & (rankings["interpreted"])].sort_values(
            ["pass_name", "target", "rank"])
        parts.append("Top five features of each interpreted pair. `shap_vs_value_rho` > 0 "
                     "means a higher feature value pushes the prediction up.\n")
        parts.append(markdown_table(top, ["pass_name", "target", "rank", "feature",
                                          "importance_share", "shap_vs_value_rho"]))

    # ---- Heuristics ----
    parts.append("## 6. Agreement with LLVM's rules (Phase 5)\n")
    agreement = read_csv("heuristic_agreement.csv")
    if agreement is None:
        parts.append(NOT_RUN)
    else:
        parts.append(
            "Expected features come from `heuristics.yaml`, frozen before any result "
            "existed. Scores are on feature clusters (`feature_clusters.csv`). "
            "p-values compare with 10,000 random rankings; `_holm` columns are corrected "
            "across interpreted pairs.\n")
        parts.append(markdown_table(agreement, [
            "pass_name", "target", "list", "interpreted", "n_expected_clusters",
            "expected_ranks", "hit_at_5", "mrr", "mrr_null_mean", "mrr_p", "mrr_p_holm", "note"]))
        pooled = read_csv("pooled_heuristic_agreement.csv")
        if pooled is not None:
            parts.append("Pooled over interpreted pairs (mean percentile rank of the expected "
                         "clusters; 0 is the top, about 0.5 is chance):\n")
            parts.append(markdown_table(pooled))
        direction = read_csv("heuristic_direction.csv")
        if direction is not None and len(direction):
            tally = direction[direction["interpreted"]].groupby("verdict").size().reset_index(name="n")
            parts.append("Direction of the expected features (interpreted pairs):\n")
            parts.append(markdown_table(tally))
        cross = read_csv("heuristic_cross_pass.csv")
        if cross is not None and len(cross):
            chosen = cross[cross["interpreted"]]
            parts.append(f"Cross-pass control: in {int(chosen['own_list_fits_better'].sum())} of "
                         f"{len(chosen)} interpreted pairs the ranking fits the pass's own "
                         "applicability list better than the lists of other passes.\n")
        thresholds = read_csv("threshold_analysis.csv")
        if thresholds is not None and len(thresholds):
            parts.append("LLVM cost-model thresholds. The features are proxies for what the "
                         "pass measures (see LIMITATIONS.md):\n")
            parts.append(markdown_table(thresholds, [
                "pass_name", "target", "interpreted", "feature", "option", "llvm_threshold",
                "feature_rank", "crossover", "mean_shap_at_or_below_threshold",
                "mean_shap_above_threshold", "n_at_or_below", "n_above"]))
        novel = read_csv("novel_drivers.csv")
        if novel is not None and len(novel):
            parts.append("Top-ranked feature clusters that `heuristics.yaml` does not list "
                         "(candidates only; a cluster that contains the size feature is "
                         "likely a size effect):\n")
            parts.append(markdown_table(novel[novel["interpreted"]], [
                "pass_name", "target", "cluster_rank", "cluster_share", "features",
                "contains_size_feature"]))

    # ---- Pruning ----
    parts.append("## 7. Smaller models (Phase 6)\n")
    pruning = read_csv("phase6_pruning_summary.csv")
    if pruning is None:
        parts.append(NOT_RUN)
    else:
        wide = pruning[pruning["method"] != "full"].pivot_table(
            index=["pass_name", "target", "k"], columns="method",
            values="share_of_full_pr_auc", sort=False).reset_index()
        parts.append("Share of the full model's PR-AUC that is kept with k features, "
                     "by the method used to choose them:\n")
        parts.append(markdown_table(wide))

    # ---- Sequences ----
    parts.append("## 8. Pass sequences on held-out programs (Phase 7)\n")
    sequence = read_csv("phase7_summary.csv")
    if sequence is None:
        parts.append(NOT_RUN)
    else:
        parts.append("Final size / starting size, geometric mean over held-out programs "
                     "(1.00 = unchanged; lower = smaller code). `model_vs_method_ratio` "
                     "below 1 means the model-guided sequence ends smaller.\n")
        parts.append(markdown_table(sequence))

    # ---- What the results do not show ----
    parts.append("## 9. What these results do not show\n")
    parts.append(
        "- **Running time.** The objective is instruction count. A smaller function is not "
        "necessarily a faster one.\n"
        "- **Causality.** SHAP describes what the model relies on, not what makes a pass "
        "work. Agreement with `heuristics.yaml` shows consistency, not that the model "
        "rediscovered LLVM's logic.\n"
        "- **Generality.** Two C benchmark suites, 53 programs, with 8 programs holding most "
        "samples. Only 496 of 1118 source files compile outside their build systems.\n"
        "- **Full phase ordering.** Each label is the effect of ONE pass on one state.\n"
        "- **Independence of folds.** Cross-validation folds share training data, so the "
        "fold-level test is optimistic; the program bootstrap is the safer number.\n"
        "- **Verified heuristics.** Entries of `heuristics.yaml` marked `verified: false` "
        "have not been checked against LLVM's source by hand.\n")

    output = RESULTS_DIR / "RESULTS.md"
    output.write_text("\n".join(parts), encoding="utf-8")
    log.info("Wrote %s", output)


if __name__ == "__main__":
    generate()
